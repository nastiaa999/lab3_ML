SYSTEM_E = """Ты — система предиктивного обслуживания станков. По описанию режима работы станка определи,
произойдёт ли отказ. Ответь ровно одной строкой: ОТВЕТ: 1 (будет отказ) или ОТВЕТ: 0 (отказа не будет)."""


def e_prompt(text, examples):
    """Промпт для типа E. examples — список пар (текст, класс); пустой список = zero-shot."""
    parts = []
    if examples:
        parts.append("Примеры с известным исходом:")
        parts += [f"{t}\nОТВЕТ: {y}" for t, y in examples]
        parts.append("Теперь новый станок:")
    parts.append(text)
    return "\n\n".join(parts)
