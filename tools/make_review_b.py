"""Бланки слепой проверки B по рубрике 0–2 (вердикт + обоснование) для двух проверяющих.

Как и make_review.py: ответы перемешаны (seed 42), коды B01..B24, имя модели не указано.
Результат: review/бланк_B_проверяющий_1.csv, review/бланк_B_проверяющий_2.csv, review/ключ_B.csv.
"""
import os
import random

import pandas as pd

# Эталонное обоснование (то же, что в Банк_задач_для_Ани.pdf)
REASON = {
    "B1": "Оптимальная инерция при k+1 кластерах не больше, чем при k: можно взять оптимальное решение для k и "
          "добавить ещё один центр — инерция не вырастет.",
    "B2": "Если выборка разделима, умножение w и b на число > 1 уменьшает log-loss на всех объектах, поэтому минимум "
          "не достигается, веса растут бесконечно. Лечится регуляризацией.",
    "B3": "PCA ищет направления максимальной дисперсии, а дисперсия зависит от единиц измерения: признак с большим "
          "масштабом «перетянет» компоненты на себя. Поэтому признаки обычно стандартизуют.",
    "B4": "Усреднение многих моделей, обученных на бутстреп-выборках, уменьшает дисперсию; смещение среднего примерно "
          "равно смещению одной модели.",
    "B5": "Решение SVM с жёстким зазором определяется только опорными векторами. Объект с |w·x+b| > 1 не влияет на "
          "оптимум, после его удаления решение не меняется.",
    "B6": "Наивный Байес считает признаки независимыми, поэтому копия признака учитывается дважды (его правдоподобие "
          "возводится в квадрат). Это может перевесить остальные признаки и сменить класс.",
}

bank = pd.read_csv("data/bank.csv").set_index("id")
ans = pd.read_csv("results/bank_answers.csv")
ans = ans[ans["type"] == "B"].reset_index(drop=True)

rng = random.Random(42)
order = []
for _, group in ans.groupby("id", sort=False):
    idx = list(group.index)
    rng.shuffle(idx)  # внутри задачи порядок моделей случайный
    order += idx
ans = ans.loc[order].reset_index(drop=True)
ans["код"] = [f"B{i + 1:02d}" for i in range(len(ans))]

blank = pd.DataFrame({
    "код": ans["код"],
    "задача": ans["id"],
    "утверждение": [bank.loc[i, "text_ru"] for i in ans["id"]],
    "эталон": [f"{bank.loc[i, 'answer']}. {REASON[i]}" for i in ans["id"]],
    "ответ модели": ans["full_text"],
    "балл B (0-2)": "",
    "комментарий": "",
})
os.makedirs("review", exist_ok=True)
for n in (1, 2):  # sep=';' и utf-8-sig — чтобы русский Excel открыл файл двойным щелчком
    blank.to_csv(f"review/бланк_B_проверяющий_{n}.csv", sep=";", index=False, encoding="utf-8-sig")
ans[["код", "id", "model"]].to_csv("review/ключ_B.csv", index=False)
print(blank[["код", "задача"]].to_string(index=False))
