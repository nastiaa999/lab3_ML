def clear_runs(p):
    for child in list(p):
        if child.tag != qn("w:pPr"):
            p.remove(child)
    return p


def runs_xml(text, base_rpr=""):
    """Текст -> набор w:r. Жирный шрифт только в заголовках, поэтому **...** просто снимается."""
    out = []
    text = text.replace("**", "").replace("—", "‒")
    for part in re.split(r"(\*\*[^*]+\*\*)", text):
        if not part:
            continue
        rpr = base_rpr
        if part.startswith("**"):
            part, rpr = part[2:-2], base_rpr + "<w:b/>"
        part = part.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
        rpr = f"<w:rPr>{rpr}</w:rPr>" if rpr else ""
        out.append(f'<w:r {W}>{rpr}<w:t xml:space="preserve">{part}</w:t></w:r>')
    return [parse_xml(x) for x in out]


def par(kind, text, base_rpr=""):
    p = clear_runs(copy.deepcopy(proto[kind]))
    for r in runs_xml(text, base_rpr):
        p.append(r)
    return add(p)


