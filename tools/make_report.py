def md_blocks(text):
    """Простейший разбор markdown: заголовки, абзацы, пункты списка, цитаты, таблицы."""
    blocks = []
    for line in text.split("\n"):
        s_ = line.rstrip()
        prev = blocks[-1] if blocks else (None, None)
        if not s_.strip() or s_ == "---":
            blocks.append(("blank", None))
        elif s_.startswith("#"):
            blocks.append(("h", s_))
        elif s_.startswith("|"):
            if prev[0] == "table":
                prev[1].append(s_)
            else:
                blocks.append(("table", [s_]))
        elif s_.startswith(">"):
            t = re.sub(r"^>\s?", "", s_)
            if prev[0] == "quote":
                blocks[-1] = ("quote", prev[1] + " " + t)
            else:
                blocks.append(("quote", t))
        elif re.match(r"^- ", s_):
            blocks.append(("li", s_[2:]))
        elif prev[0] in ("li", "p") and (s_.startswith("  ") or prev[0] == "p"):
            blocks[-1] = (prev[0], prev[1] + " " + s_.strip())
        else:
            blocks.append(("p", s_.strip()))
    return [b for b in blocks if b[0] != "blank"]


def md_table(lines, caption, widths, size=20):
    rows = [[c.strip() for c in ln.strip("|").split("|")] for ln in lines if not re.match(r"^\|\s*-", ln)]
    rows = [[c.replace("\\|", "|") for c in r] for r in rows]
    table(caption, rows[0], rows[1:], widths, size=size)


