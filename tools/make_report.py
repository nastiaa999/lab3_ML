def heading(kind, text, level):
    p = clear_runs(copy.deepcopy(proto[kind]))
    name = f"_rep{bm[0]}"
    p.append(parse_xml(f'<w:bookmarkStart {W} w:id="{bm[0]}" w:name="{name}"/>'))
    for r in runs_xml(text):
        p.append(r)
    p.append(parse_xml(f'<w:bookmarkEnd {W} w:id="{bm[0]}"/>'))
    bm[0] += 1
    toc.append((level, text, name))
    return add(p)


